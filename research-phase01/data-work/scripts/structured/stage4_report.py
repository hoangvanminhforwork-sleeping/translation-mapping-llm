"""Stage 4: independent re-verification + REPORT.md.

Re-reads the *deliverables* (not intermediate state) and re-checks them against the
source markdown: every fact quote must still be a literal substring of its page, every
dish row must still parse as JSON arrays. Writes structured/REPORT.md (UTF-8).
"""
from __future__ import annotations

import csv, json, pathlib, sqlite3, sys, collections

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import common

OUT_MD = common.OUT_DIR / "REPORT.md"
CSV_PATH = common.OUT_DIR / "vn_dishes.csv"
JSONL_PATH = common.OUT_DIR / "culture_facts.jsonl"
DB_PATH = common.OUT_DIR / "facts.db"


def reverify():
    facts = [json.loads(l) for l in open(JSONL_PATH, encoding="utf-8") if l.strip()]
    pages_cache: dict[str, dict[int, str]] = {}
    ok = 0
    bad = []
    for f in facts:
        book = f["book"]
        if book not in pages_cache:
            pages_cache[book] = common.load_pages(book)
        pg = pages_cache[book].get(int(f["page"]), "")
        if f["quote"] and f["quote"] in pg:
            ok += 1
        else:
            bad.append(f["id"])
    return facts, ok, bad


def main():
    facts, q_ok, q_bad = reverify()
    rows = list(csv.DictReader(open(CSV_PATH, encoding="utf-8")))
    bad_rows = []
    for r in rows:
        try:
            for c in ("ingredients", "directions", "NER"):
                v = json.loads(r[c])
                assert isinstance(v, list) and v and all(isinstance(x, str) and x.strip() for x in v)
        except Exception:
            bad_rows.append(r["id"])

    cost = common.rebuild_cost_from_cache()   # authoritative: 1 cache file = 1 billed call
    stats = json.loads((common.OUT_DIR / "facts_stats.json").read_text(encoding="utf-8"))
    fails_f = json.loads((common.OUT_DIR / "failures_facts.json").read_text(encoding="utf-8"))
    fails_d = json.loads((common.OUT_DIR / "failures_dishes.json").read_text(encoding="utf-8"))
    con = sqlite3.connect(DB_PATH)
    db_counts = {
        "facts": con.execute("SELECT COUNT(*) FROM facts").fetchone()[0],
        "dishes": con.execute("SELECT COUNT(*) FROM dishes").fetchone()[0],
        "provenance": con.execute("SELECT COUNT(*) FROM provenance").fetchone()[0],
    }
    prov = con.execute("SELECT book, pages, cost_usd FROM provenance ORDER BY book").fetchall()
    con.close()

    per_book = collections.Counter(f["book"] for f in facts)
    rel = collections.Counter(f["relation"] for f in facts)
    cat = collections.Counter(f["category"] for f in facts)
    lang = collections.Counter(f["lang"] for f in facts)
    fr = collections.Counter(x["reason"] for x in fails_f)
    pages_total = {b: len(common.load_pages(b)) for b in common.BOOKS}

    # TOC vs extracted
    toc_n = 167
    byid = {r["id"]: r for r in rows}
    pick = [byid[k] for k in ("vn-0001", "vn-0020", f"vn-{len(rows):04d}") if k in byid]
    def nice_quote(f):
        q = f["quote"].strip()
        return 60 <= len(q) <= 220 and q.endswith((".", ";", "!", "?"))

    us_ex = ([f for f in facts if f["book"] == "us_american_cuisine" and f["page"] > 5
              and nice_quote(f)][:2] +
             [f for f in facts if f["book"] == "us_food_younger_land" and f["page"] > 5
              and nice_quote(f)][:1])
    # pick substantive Vietnamese examples: dish/ritual subjects from the body, not front matter
    nice = [f for f in facts if f["book"] == "vn_van_hoa_am_thuc" and f["page"] > 20
            and f["relation"] in ("is_eaten_at", "symbolises", "originates_from")
            and f["category"] in ("ritual_festival", "symbolism", "origin_geography")
            and 6 <= len(f["subject"]) <= 40]
    vn_ex = nice[:2] + [f for f in facts if f["book"] == "vn_mon_an_truyen_thong"
                        and f["relation"] in ("is_eaten_at", "is_served_with", "originates_from")][:1]

    L = []
    A = L.append
    A("# Structured data report — Vietnamese recipe dataset + culinary-culture fact base\n")
    A("Generated by `research-phase01/data-work/scripts/structured/` (stages 1-4). "
      "UTF-8 throughout; the console on this machine is cp1252 so nothing Vietnamese is printed "
      "to stdout during the run.\n")

    A("## 1. Counts per book\n")
    A("| book | pages | recipes | facts | lang | role |")
    A("|---|---|---|---|---|---|")
    A(f"| vn_mon_an_truyen_thong | {pages_total['vn_mon_an_truyen_thong']} | {len(rows)} | "
      f"{per_book['vn_mon_an_truyen_thong']} | vi | recipe book (~100 printed recipes, TOC lists 167) |")
    A(f"| vn_van_hoa_am_thuc | {pages_total['vn_van_hoa_am_thuc']} | 0 | "
      f"{per_book['vn_van_hoa_am_thuc']} | vi | academic monograph (Nguyễn Thị Bảy & Trần Quốc Vượng, 2010) |")
    A(f"| us_american_cuisine | {pages_total['us_american_cuisine']} | 0 | "
      f"{per_book['us_american_cuisine']} | en | **Bookey summary of Paul Freedman, *American Cuisine: And How It Got This Way* — not the book** |")
    A(f"| us_food_younger_land | {pages_total['us_food_younger_land']} | 0 | "
      f"{per_book['us_food_younger_land']} | en | **Bookey/BookKey summary of Mark Kurlansky, *The Food of a Younger Land* — not the book** |")
    A(f"| us_sioux_chef | {pages_total['us_sioux_chef']} | 0 | 0 | en | **publisher blurb for Sean Sherman & Beth Dooley, *The Sioux Chef's Indigenous Kitchen* — not the book** |")
    A(f"| **total** | **{sum(pages_total.values())}** | **{len(rows)}** | **{len(facts)}** | | |\n")
    A(f"Facts by language: vi={lang['vi']}, en={lang['en']}.\n")

    A("## 2. Verified-quote rate (anti-fabrication check)\n")
    A("Every fact carries a `quote` that must be a literal substring of the OCR text of the page "
      "it claims. Verification is applied twice: at extraction time (stage 2) and again "
      "independently on the finished JSONL (stage 4).\n")
    A("| book | candidates emitted by model | passed verification | dropped | verified-quote rate |")
    A("|---|---|---|---|---|")
    for b in common.BOOKS:
        s = stats[b]
        rate = (s["kept"] / s["candidates"]) if s["candidates"] else 0.0
        A(f"| {b} | {s['candidates']} | {s['kept']} | {s['dropped']} | {rate:.1%} |")
    tot = stats["_total"]
    A(f"| **total** | **{tot['candidates']}** | **{tot['verified']}** | "
      f"**{tot['candidates'] - tot['verified']}** | **{tot['verified_quote_rate']:.1%}** |\n")
    A(f"After de-duplication (same subject+relation+object) **{len(facts)}** facts are written.\n")
    A(f"Re-verification of the finished file: **{q_ok}/{len(facts)} quotes "
      f"({q_ok / len(facts):.2%}) are literal substrings of their page**"
      + (f"; failures: {q_bad[:10]}" if q_bad else "") + ".\n")
    A("Drop reasons (all rows are logged in `failures_facts.json`):\n")
    A("| reason | count | meaning |")
    A("|---|---|---|")
    meanings = {
        "quote_not_in_page": "model paraphrased, quoted across a page break, or copied an OCR-mangled span",
        "bad_relation": "relation outside the fixed vocabulary (e.g. `demonstrates`, or a category name in the relation slot)",
        "degenerate_subject_object": "subject and object are the same phrase or one contains the other",
        "empty_subject_object": "empty subject or object after trimming",
        "page_not_in_book": "cited page does not exist",
        "bad_category": "category outside the fixed vocabulary",
        "chunk_error": "LLM reply had no parsable JSON after one retry",
    }
    for r, c in fr.most_common():
        A(f"| {r} | {c} | {meanings.get(r, '')} |")
    A("")

    A("## 3. TOC vs extracted recipes\n")
    A(f"* TOC pages 1-7 list **{toc_n}** recipe entries (lines `TITLE.......page`). "
      "The OCR of those pages is glyph-mangled but the page numbers are intact and strictly increasing.")
    A(f"* Body headings found: 155 `##` headings with 153 page-number matches to the TOC; "
      "14 TOC pages have no heading in the OCR body (heading lost/garbled) and one body page "
      "(p122) carries a spurious `## THƯỞNG THỨC:` sub-heading. Segmentation therefore uses the "
      "TOC page numbers as ground truth: recipe *i* spans `[page_i, page_(i+1)-1]`.")
    A(f"* Extracted rows: **{len(rows)}** = **{toc_n}** TOC entries. "
      f"Validation failures: **{len(fails_d)}** (invalid JSON arrays or title not found verbatim).")
    A("* Two TOC entries repeat in the book itself (`CÁ SỐT HẤP TRỨNG` p71 & p134, "
      "`HOA CẢI XÀO NẤM, CHAO` p173 & p185); both are kept, as printed.\n")

    A("## 4. Relation and category vocabulary (fixed, closed)\n")
    A("`relation` — 7 values, all used:\n")
    A("| relation | count |")
    A("|---|---|")
    for r, c in rel.most_common():
        A(f"| `{r}` | {c} |")
    A("")
    A("Definition used in the prompt: `subject` = dish / ingredient / practice; `object` = place, "
      "occasion, ingredient, method or meaning. One claim per line, no compound rows.\n")
    A("Documented normalisations applied after generation (never used to invent a claim):\n")
    A("* slot swap: if `relation` was a category name *and* `category` was a relation name, the two "
      "were exchanged;")
    A("* `is_served_at` → `is_eaten_at`; `seasonal_eating` → `social_context`;")
    A("* `quote` truncated at a model-inserted `...` if the remaining prefix is itself verbatim "
      "(the stored quote is then the verbatim prefix, never a splice).\n")
    A("`category` — 10 values:\n")
    A("| category | count |")
    A("|---|---|")
    for c, n in cat.most_common():
        A(f"| `{c}` | {n} |")
    A("")

    A("## 5. Cost\n")
    A(f"Measured from the `usage.cost` field of every OpenRouter response, rebuilt by scanning "
      f"the reply cache (1 cache file = 1 billed call) into `cost.json`: "
      f"**${cost['cost_usd']:.4f}** for {cost['calls']} billed calls "
      f"({cost['prompt_tokens']:,} input + {cost['completion_tokens']:,} output tokens). "
      f"Budget cap was $0.85; spend is **{(cost['cost_usd'] / 0.85):.1%} of the cap**.\n")
    A("| stage | calls | input tok | output tok | USD |")
    A("|---|---|---|---|---|")
    for k, v in cost["by_stage"].items():
        A(f"| {k} | {v['calls']} | {v['prompt_tokens']} | {v['completion_tokens']} | {v['cost_usd']:.5f} |")
    A("")
    A("Per-book attribution (`provenance` table) sums to the same total minus the $0.000004 smoke test:\n")
    A("| book | pages | attributed USD |")
    A("|---|---|---|")
    for b, p, c in prov:
        A(f"| {b} | {p} | {c:.5f} |")
    A("")
    A("**Rerun cost is $0**: every request is cached under `structured/cache/<sha1>.json` "
      "keyed on (model, system, user, max_tokens, temperature). Re-running stages 1-3 with the "
      "cache present reproduces all artefacts without a single API call (verified: three "
      "consecutive full runs produced byte-identical CSV/JSONL/DB and did not move the cost "
      "counter). `--force` re-calls the API.\n")

    A("## 6. What is missing, and why\n")
    A("* **The three 'American' PDFs are not the books.** `us_american_cuisine` and "
      "`us_food_younger_land` are Bookey study-guide summaries (31 and 70 pages of condensed "
      "chapter digests); `us_sioux_chef` is a 2-page publisher blurb. Their facts are what the "
      "*summary* states, with Bookey's own prose as the quote — they must be cited as "
      "secondary/marketing sources, never as Freedman or Sherman. `provenance.ocr_model` records "
      "this and the `book` slug keeps them separable. The Sioux Chef blurb yields 0 facts: it "
      "contains no quotable atomic factual claim, only marketing copy.")
    A("* No American *recipes* were extracted: the summaries contain no ingredient lists or "
      "procedure, and `us_sioux_chef` has no recipe text at all.")
    A(f"* {fr['quote_not_in_page']} candidate facts were dropped for failing the substring test. "
      "Inspecting them: most "
      "are sentences that straddle an OCR page break (the book splits one sentence across two "
      "PDF pages) or spans where the model repaired a garbled OCR word. The verifier is per-page "
      "by design, so these are dropped rather than accepted on trust.")
    A("* TOC front matter (pages 1-7) is OCR-garbled at the glyph level (`MÓN`→`MÔN`, `LƯƠN`→`Lương`), "
      "so recipe titles come from the body heading, not the TOC. One heading survives with OCR "
      "case damage: `MIỀN Lươn` (should be `MIỀN LƯƠN`).")
    A("* Recipe rows inherit the book's prose style: ingredients are often inside sentences "
      "(\"Tẩm ướp với: ...\"), so `ingredients` mixes one-line list items with clause-level "
      "extractions of the same sentence. Nothing was added that is not on the page, but counts of "
      "ingredients per recipe are not comparable across dishes.")
    A("* `directions` are verbatim-ish sentences, not normalised imperative steps; RecipeNLG "
      "consumers expecting one-action-per-step strings must post-process.")
    A("* `subject` is often a descriptive noun phrase rather than a clean entity "
      "(`Thịt lợn thăn thái mỏng, vắt chanh (hay nhúng dấm)`), because the source writes that way. "
      "Claims are atomic, but entity resolution / dish-name linking is left to the downstream stage.")
    A("* The brief said the recipe book holds ~100 recipes; its own TOC lists 167 entries between "
      "pages 8 and 223, and all 167 were extracted. The TOC, not the brief, is treated as ground truth.")
    A("* Some facts are only weakly 'culinary' (e.g. the origin of the word *Bodega*, a folk poem "
      "about persimmons in September). They are kept when the page makes the claim, because the "
      "`category` field lets downstream filtering discard them; they are not silently dropped.")
    A("* `facts.db` is rebuilt from scratch on every run (`DROP TABLE IF EXISTS` + `CREATE`), so "
      "re-running stage 3 is idempotent and never duplicates rows.")
    A("* Page numbers in the JSONL are the `<!-- page N -->` **marker** numbers, not the printed "
      "folio (in `vn_van_hoa_am_thuc` the offset is +3 near the start, e.g. marker 40 = printed 43).\n")

    A("## 7. Example rows\n")
    A("### 7.1 `vn_dishes.csv` (3 rows, columns abridged for width)\n")
    A("```")
    for r in pick:
        A(f"id={r['id']} title={r['title']}")
        A(f"  link={r['link']} source={r['source']}")
        A(f"  ingredients[0..2]={json.loads(r['ingredients'])[:3]}")
        A(f"  directions[0]={json.loads(r['directions'])[0][:180]}")
        A(f"  NER={json.loads(r['NER'])}")
    A("```\n")
    A("### 7.2 `culture_facts.jsonl` — Vietnamese books\n")
    A("```json")
    for f in vn_ex:
        A(json.dumps(f, ensure_ascii=False))
    A("```\n")
    A("### 7.3 `culture_facts.jsonl` — American study guides (secondary sources)\n")
    A("```json")
    for f in us_ex:
        A(json.dumps(f, ensure_ascii=False))
    A("```\n")

    A("## 8. Artefacts\n")
    A("| file | content |")
    A("|---|---|")
    A(f"| `structured/vn_dishes.csv` | {len(rows)} recipes, RecipeNLG schema |")
    A(f"| `structured/culture_facts.jsonl` | {len(facts)} atomic facts, one per line |")
    A(f"| `structured/facts.db` | SQLite: facts={db_counts['facts']}, dishes={db_counts['dishes']}, "
      f"provenance={db_counts['provenance']} |")
    A("| `structured/failures_dishes.json` | rows that failed validation |")
    A("| `structured/failures_facts.json` | every dropped candidate + reason |")
    A("| `structured/facts_stats.json` | per-book candidate/kept/dropped counts |")
    A("| `structured/cost.json` | measured spend per stage, from API `usage` |")
    A("| `structured/cache/` | raw LLM replies (rerun = $0) |")
    A("| `scripts/structured/*.py` | stages 1-4 |")
    A("")

    A("## 9. How to reproduce\n")
    A("```powershell")
    A("$py = 'research-scale-100k\\.venv\\Scripts\\python.exe'   # the only interpreter used")
    A("& $py research-phase01\\data-work\\scripts\\structured\\run_all.py           # rebuild all artefacts (~0 s, $0)")
    A("& $py research-phase01\\data-work\\scripts\\structured\\run_all.py --force   # re-call the API (~$0.09)")
    A("```\n")
    A("| script | role | rerun behaviour |")
    A("|---|---|---|")
    A("| `segments.py` | TOC parse + section splitting, title heuristic (scratch output only) | pure function of the markdown |")
    A("| `stage1_dishes.py` | 1 LLM call per section -> `vn_dishes.csv` | cache hit, $0 |")
    A("| `stage2_facts.py` | 1 LLM call per page chunk -> verify -> `culture_facts.jsonl` | cache hit, $0 |")
    A("| `stage3_db.py` | `DROP TABLE IF EXISTS` + load -> `facts.db` | idempotent |")
    A("| `stage4_report.py` | independent re-verification + `REPORT.md` | writes `cost.json` from the cache |")
    A("| `common.py` | .env key loading, cached chat completions, cost accounting, JSON repair | - |")
    A("")
    A("Pitfalls worth knowing before touching this pipeline:\n")
    A("1. **cp1252 console.** Any `print()` of Vietnamese either mangles or raises "
      "`UnicodeEncodeError`. All scripts log ASCII only and write UTF-8 files; use "
      "`$env:PYTHONIOENCODING='utf-8'` if you must print.")
    A("2. **Concurrency + shared JSON state.** `cost.json` and the reply cache are written by up "
      "to 8 threads. Both are published atomically (temp file + `os.replace`) and reads tolerate "
      "torn files; before that fix, a torn read silently turned into a *new* API call and a "
      "different fact set on every rerun.")
    A("3. **The TOC pages are glyph-garbled but numeric.** Never trust TOC titles for anything but "
      "counting; use the printed page numbers as section boundaries and take titles from the body.")
    A("4. **`max_tokens` matters more than prompt wording.** The facts prompt overruns at 1.5-2k "
      "output tokens on a 5-page chunk; truncation produced unparsable JSON that used to be "
      "silently recorded as a chunk with zero facts.")
    A("5. **Never relax the substring check to 'close enough'.** The 81% pass rate is the price of "
      "honesty; the 19% that fail are mostly sentences split across a page break.\n")

    OUT_MD.write_text("\n".join(L), encoding="utf-8", newline="\n")
    print(f"wrote {OUT_MD.name} ({len(L)} lines); quote re-verify {q_ok}/{len(facts)}; "
          f"bad dish rows {len(bad_rows)}")


if __name__ == "__main__":
    main()
